end $$;

-- Plain-text summary used for email and Discord. Empty string = nothing worth reporting.
create or replace function private.alerts_text() returns text
language plpgsql stable security definer set search_path = '' as $$
declare a jsonb := private.alerts(); t text := ''; x jsonb;
begin
  if jsonb_array_length(a->'low_hours') > 0 then
    t := t || format(E'LOW HOURS (%s members below their weekly requirement)\n', jsonb_array_length(a->'low_hours'));
    for x in select * from jsonb_array_elements(a->'low_hours') loop
      t := t || format(E'  - %s (%s): %s / %s h\n', x->>'name', x->>'rank', x->>'hours', x->>'required');
    end loop;
    t := t || E'\n';
  end if;
  if (a->>'trainings_7d')::int < (a->>'min_trainings')::numeric then
    t := t || format(E'FEW TRAININGS: %s hosted in the last 7 days (goal %s)\n\n', a->>'trainings_7d', a->>'min_trainings');
  end if;
  if (a->>'tryouts_7d')::int < (a->>'min_tryouts')::numeric then
    t := t || format(E'FEW TRYOUTS: %s held in the last 7 days (goal %s)\n\n', a->>'tryouts_7d', a->>'min_tryouts');
  end if;
  if jsonb_array_length(a->'training_overdue') > 0 then
    t := t || E'NCOS WITHOUT A TRAINING IN 14 DAYS\n';
    for x in select * from jsonb_array_elements(a->'training_overdue') loop
      t := t || format(E'  - %s (%s)\n', x->>'name', x->>'rank'); end loop;
    t := t || E'\n';
  end if;
  if jsonb_array_length(a->'pending_requests') > 0 then
    t := t || format(E'LEAVE REQUESTS WAITING: %s\n', jsonb_array_length(a->'pending_requests'));
    for x in select * from jsonb_array_elements(a->'pending_requests') loop
      t := t || format(E'  - %s: %s %s to %s\n', x->>'name', x->>'type', x->>'starts_on', x->>'ends_on'); end loop;
    t := t || E'\n';
  end if;
  if jsonb_array_length(a->'leave_ending') > 0 then
    t := t || E'LEAVE ENDING TODAY OR TOMORROW\n';
    for x in select * from jsonb_array_elements(a->'leave_ending') loop
      t := t || format(E'  - %s (%s ends %s)\n', x->>'name', x->>'type', x->>'ends_on'); end loop;
    t := t || E'\n';
  end if;
  if jsonb_array_length(a->'ready_for_promotion') > 0 then
    t := t || E'READY FOR PROMOTION (all requirements met)\n';
    for x in select * from jsonb_array_elements(a->'ready_for_promotion') loop
      t := t || format(E'  - %s (%s)\n', x->>'name', x->>'rank'); end loop;
  end if;
  return trim(t);
end $$;

-- Daily report: email through Resend (API key + address in the Vault/config) and a short Discord summary.
create or replace function private.send_daily_alerts() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare body text := private.alerts_text(); api_key text; addr text; sent_mail boolean := false; a jsonb;
begin
  if body = '' then return jsonb_build_object('sent', false, 'reason', 'nothing to report'); end if;
  select decrypted_secret into api_key from vault.decrypted_secrets where name = 'nu7_resend_api_key';
  select c.value into addr from private.config c where c.key = 'alert_email';
  if api_key is not null and addr is not null then
    perform net.http_post(url := 'https://api.resend.com/emails',
      body := jsonb_build_object('from', 'Nu-7 Roster <onboarding@resend.dev>', 'to', jsonb_build_array(addr),
                                 'subject', 'Nu-7 roster alerts ' || to_char(public.app_today(), 'DD/MM/YYYY'),
                                 'text', body || E'\n\nRoster: https://einfachmia161.github.io/roster/'),
      headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || api_key));
    sent_mail := true;
  end if;
  a := private.alerts();
  perform private.discord_post(format('📋 **Daily roster check** · low hours: %s · trainings (7 d): %s · tryouts (7 d): %s · leave requests waiting: %s · ready for promotion: %s',
    jsonb_array_length(a->'low_hours'), a->>'trainings_7d', a->>'tryouts_7d',
    jsonb_array_length(a->'pending_requests'), jsonb_array_length(a->'ready_for_promotion')));
  return jsonb_build_object('sent', true, 'email', sent_mail);
end $$;


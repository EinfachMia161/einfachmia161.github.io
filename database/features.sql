create or replace function private.officer_name() returns text
language sql stable security definer set search_path = '' as $$
  select p.display_name from public.officer_account oa join public.person p on p.id = oa.person_id
  where oa.user_id = auth.uid()
$$;

-- Steam ID + Discord username check for the members area. Failures are counted and lock the Steam ID.
create or replace function private.identify(p_steam text, p_discord text, p_categories int[]) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  sid text := regexp_replace(upper(trim(coalesce(p_steam, ''))), '^STEAM_1', 'STEAM_0');
  r record;
begin
  if (select count(*) from private.attempt where kind = 'identity' and key = sid and not ok
        and at > now() - interval '15 minutes') >= 5
     or (select count(*) from private.attempt where kind = 'identity' and not ok
        and at > now() - interval '15 minutes') >= 60 then
    return jsonb_build_object('ok', false, 'message', 'Too many failed attempts. Try again in 15 minutes.');
  end if;
  select p.id as person_id, p.display_name, m.id as membership_id, m.rank_id, rk.code as rank, rk.category_id
    into r
  from public.person p
  join public.membership m on m.person_id = p.id and m.left_at is null
  join public.rank rk on rk.id = m.rank_id
  where p.steam_id = sid and p.discord_username is not null
    and lower(trim(p.discord_username)) = lower(trim(coalesce(p_discord, '')))
    and rk.category_id = any(p_categories);
  if r.person_id is null then
    insert into private.attempt (kind, key, ok) values ('identity', sid, false);
    return jsonb_build_object('ok', false, 'message',
      'Steam ID and Discord username do not match a serving member who can use this form.');
  end if;
  return jsonb_build_object('ok', true, 'person_id', r.person_id, 'name', r.display_name,
    'membership_id', r.membership_id, 'rank_id', r.rank_id, 'rank', r.rank, 'category_id', r.category_id);
end $$;

-- Posts a message to the Discord webhook stored in the Vault (if one is set). Mentions are disabled,
-- so names in messages can never ping @everyone or roles.
create or replace function private.discord_post(p_text text) returns void
language plpgsql security definer set search_path = '' as $$
declare url text;
begin
  select decrypted_secret into url from vault.decrypted_secrets where name = 'nu7_discord_webhook';
  if url is null or url !~ '^https://(discord\.com|discordapp\.com)/api/webhooks/' then return; end if;
  perform net.http_post(url := url,
    body := jsonb_build_object('content', left(p_text, 1990), 'allowed_mentions', jsonb_build_object('parse', '[]'::jsonb)),
    headers := '{"Content-Type": "application/json"}'::jsonb);
exception when others then
  null;  -- a notification must never block a roster change
end $$;

-- ===================================================================== members area (no login)
create or replace function public.my_file(p_steam_id text, p_discord text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare who jsonb; mid uuid; pid uuid; res jsonb;
begin
  who := private.identify(p_steam_id, p_discord, array[1, 2, 3, 4]);
  if not (who->>'ok')::boolean then return who; end if;
  mid := (who->>'membership_id')::uuid; pid := (who->>'person_id')::uuid;
  select jsonb_build_object(
      'ok', true, 'name', r.display_name, 'rank', r.rank_name, 'status', r.status, 'hours', r.hours,
      'required', r.weekly_hours_required, 'strikes', r.strikes, 'on_cooldown', r.on_cooldown,
      'last_promotion', r.last_promotion, 'leave_type', r.leave_type, 'leave_ends_on', r.leave_ends_on)
    into res from public.v_roster r where r.membership_id = mid;
  res := res || jsonb_build_object(
    'requirements', coalesce((select jsonb_agg(jsonb_build_object('title', b.title, 'met', b.met) order by b.sort_order)
                              from public.v_promotion_board b where b.membership_id = mid), '[]'::jsonb),
    'duty', coalesce((select jsonb_agg(x) from (select logged_on, hours, comment, source, rejected from public.duty_log
                      where person_id = pid order by logged_on desc, id desc limit 10) x), '[]'::jsonb),
    'strike_list', coalesce((select jsonb_agg(x) from (select issued_on, expires_on, weight, reason from public.strike
                      where person_id = pid and appeal_status <> 'granted' and (expires_on is null or expires_on > public.app_today())
                      order by issued_on desc) x), '[]'::jsonb),
    'requests', coalesce((select jsonb_agg(x) from (select type, starts_on, ends_on, status, decision_note from public.leave_request
                      where person_id = pid order by requested_at desc limit 5) x), '[]'::jsonb));
  return res;
end $$;

create or replace function public.request_leave(p_steam_id text, p_discord text, p_type text, p_starts date,
                                                p_ends date, p_reason text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare who jsonb; pid uuid; today date := public.app_today();
begin
  who := private.identify(p_steam_id, p_discord, array[1, 2, 3, 4]);
  if not (who->>'ok')::boolean then return who; end if;
  pid := (who->>'person_id')::uuid;
  if p_type not in ('LOA', 'ROA') then return jsonb_build_object('ok', false, 'message', 'Choose LOA or ROA.'); end if;
  if p_starts is null or p_ends is null or p_ends < p_starts then
    return jsonb_build_object('ok', false, 'message', 'The end date must be on or after the start date.'); end if;
  if p_starts < today - 1 or p_starts > today + 90 then
    return jsonb_build_object('ok', false, 'message', 'The start date must be between yesterday and 90 days from now.'); end if;
  if p_ends - p_starts > 60 then return jsonb_build_object('ok', false, 'message', 'Leave can be at most 60 days. Talk to an officer for longer.'); end if;
  if length(coalesce(p_reason, '')) > 300 then return jsonb_build_object('ok', false, 'message', 'Keep the reason under 300 characters.'); end if;
  if exists (select 1 from public.leave_request where person_id = pid and status = 'pending') then
    return jsonb_build_object('ok', false, 'message', 'You already have a request waiting for an officer.'); end if;
  insert into public.leave_request (person_id, type, starts_on, ends_on, reason)
  values (pid, p_type, p_starts, p_ends, nullif(trim(p_reason), ''));
  perform private.discord_post(format('📝 %s request from **%s** (%s): %s to %s',
    p_type, who->>'name', who->>'rank', to_char(p_starts, 'DD/MM'), to_char(p_ends, 'DD/MM')));
  return jsonb_build_object('ok', true, 'message', 'Request sent. An officer will approve or decline it.');
end $$;

create or replace function public.decide_leave_request(p_id bigint, p_approve boolean, p_note text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare rq public.leave_request; lid bigint; who text := private.officer_name();
begin
  if not public.is_officer() then raise exception 'Only signed-in officers can decide leave requests.'; end if;
  select * into rq from public.leave_request where id = p_id for update;
  if rq.id is null or rq.status <> 'pending' then raise exception 'This request has already been decided.'; end if;
  if p_approve then
    insert into public.leave (person_id, type, requested_on, starts_on, ends_on, reason, approved_by_raw, officer_note)
    values (rq.person_id, rq.type, rq.requested_at::date, rq.starts_on, rq.ends_on, rq.reason, who, nullif(trim(p_note), ''))
    returning id into lid;
  end if;
  update public.leave_request set status = case when p_approve then 'approved' else 'declined' end,
    decided_at = now(), decided_by = auth.uid(), decided_by_name = who, decision_note = nullif(trim(p_note), ''), leave_id = lid
  where id = p_id;
  return jsonb_build_object('ok', true, 'message', case when p_approve then 'Approved' else 'Declined' end);
end $$;

-- Trainings: hosted by CPL and above. Officers can log for any host; others prove who they are.
create or replace function public.log_training(p_host_steam_id text, p_host_discord text, p_type_id int, p_held_on date,
                                               p_attendees uuid[], p_description text default null,
                                               p_comment text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare who jsonb; host uuid; hname text; tid bigint; n int; tname text; today date := public.app_today();
begin
  if public.is_officer() and coalesce(trim(p_host_discord), '') = '' then
    select p.id, p.display_name into host, hname from public.person p
      join public.membership m on m.person_id = p.id and m.left_at is null
      join public.rank r on r.id = m.rank_id
     where p.steam_id = regexp_replace(upper(trim(p_host_steam_id)), '^STEAM_1', 'STEAM_0') and r.category_id in (1, 2, 3);
    if host is null then return jsonb_build_object('ok', false, 'message', 'The host must be a serving CPL or above.'); end if;
  else
    who := private.identify(p_host_steam_id, p_host_discord, array[1, 2, 3]);
    if not (who->>'ok')::boolean then return who; end if;
    host := (who->>'person_id')::uuid; hname := who->>'name';
  end if;
  select name into tname from public.training_type where id = p_type_id;
  if tname is null then return jsonb_build_object('ok', false, 'message', 'Choose a training type.'); end if;
  if tname = 'Unlisted' and coalesce(trim(p_description), '') = '' then
    return jsonb_build_object('ok', false, 'message', 'Describe the training when the type is Unlisted.'); end if;
  if p_held_on is null or p_held_on > today or p_held_on < today - 6 then
    return jsonb_build_object('ok', false, 'message', 'The date must be today or within the last 6 days.'); end if;
  if length(coalesce(p_description, '')) > 300 or length(coalesce(p_comment, '')) > 1000 then
    return jsonb_build_object('ok', false, 'message', 'Description or comment is too long.'); end if;
  select count(*) into n from public.membership m where m.left_at is null and m.person_id = any(p_attendees) and m.person_id <> host;
  if n < 1 or n > 40 or n <> cardinality(array(select distinct unnest(p_attendees))) - (case when host = any(p_attendees) then 1 else 0 end) then
    return jsonb_build_object('ok', false, 'message', 'Pick 1 to 40 serving members as attendees (not the host).'); end if;
  if (select count(*) from public.training where host_id = host and held_on > today - 1) >= 10 then
    return jsonb_build_object('ok', false, 'message', 'Daily limit of 10 trainings reached.'); end if;
  insert into public.training (host_id, type_id, held_on, description, comment)
  values (host, p_type_id, p_held_on, nullif(trim(p_description), ''), nullif(trim(p_comment), '')) returning id into tid;
  insert into public.training_attendee (training_id, person_id, raw_name)
  select tid, p.id, p.display_name from public.person p where p.id = any(p_attendees) and p.id <> host
    and exists (select 1 from public.membership m where m.person_id = p.id and m.left_at is null);
  return jsonb_build_object('ok', true, 'message', format('%s logged for %s with %s attendees', tname, hname, n));
end $$;

-- Tryouts: hosted by CPL and above. A pass for a blacklisted Steam ID can only be logged by an officer.
create or replace function public.log_tryout(p_host_steam_id text, p_host_discord text, p_recruit_name text,
                                             p_recruit_steam_id text, p_recruit_discord text, p_result text,
                                             p_score int default null, p_comment text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare who jsonb; host uuid; hname text; rid uuid; tid bigint; officer boolean := public.is_officer();
        rsid text := regexp_replace(upper(trim(coalesce(p_recruit_steam_id, ''))), '^STEAM_1', 'STEAM_0');
        today date := public.app_today(); blacklisted boolean;
begin
  if officer and coalesce(trim(p_host_discord), '') = '' then
    select p.id, p.display_name into host, hname from public.person p
      join public.membership m on m.person_id = p.id and m.left_at is null
      join public.rank r on r.id = m.rank_id
     where p.steam_id = regexp_replace(upper(trim(p_host_steam_id)), '^STEAM_1', 'STEAM_0') and r.category_id in (1, 2, 3);
    if host is null then return jsonb_build_object('ok', false, 'message', 'The host must be a serving CPL or above.'); end if;
  else
    who := private.identify(p_host_steam_id, p_host_discord, array[1, 2, 3]);
    if not (who->>'ok')::boolean then return who; end if;
    host := (who->>'person_id')::uuid; hname := who->>'name';
  end if;
  if rsid !~ '^STEAM_0:[01]:[0-9]+$' then return jsonb_build_object('ok', false, 'message', 'Recruit Steam ID must look like STEAM_0:1:12345678.'); end if;
  if coalesce(trim(p_recruit_name), '') = '' or length(p_recruit_name) > 80 then
    return jsonb_build_object('ok', false, 'message', 'Enter the recruit''s name.'); end if;
  if p_result not in ('passed', 'failed') then return jsonb_build_object('ok', false, 'message', 'Choose passed or failed.'); end if;
  if p_score is not null and (p_score < 0 or p_score > 12) then return jsonb_build_object('ok', false, 'message', 'The quiz score must be between 0 and 12.'); end if;
  if length(coalesce(p_comment, '')) > 1000 then return jsonb_build_object('ok', false, 'message', 'The comment is too long.'); end if;
  if exists (select 1 from public.person p join public.membership m on m.person_id = p.id and m.left_at is null where p.steam_id = rsid) then
    return jsonb_build_object('ok', false, 'message', 'This recruit is already on the roster.'); end if;
  blacklisted := exists (select 1 from public.v_active_blacklist where steam_id = rsid);
  if blacklisted and p_result = 'passed' and not officer then
    return jsonb_build_object('ok', false, 'message', 'This Steam ID is blacklisted. Only an officer can log a pass.'); end if;
  if (select count(*) from public.tryout where host_id = host and held_on > today - 1) >= 20 then
    return jsonb_build_object('ok', false, 'message', 'Daily limit of 20 tryouts reached.'); end if;
  select id into rid from public.person where steam_id = rsid;
  if rid is null then
    insert into public.person (steam_id, display_name, discord_username)
    values (rsid, trim(p_recruit_name), nullif(trim(p_recruit_discord), '')) returning id into rid;
  end if;
  insert into public.person_alias (person_id, name, first_seen) values (rid, trim(p_recruit_name), today) on conflict do nothing;
  insert into public.tryout (recruit_id, host_id, held_on, result, comment)
  values (rid, host, today, p_result, nullif(trim(p_comment), '')) returning id into tid;
  if p_score is not null then
    insert into public.tryout_quiz (tryout_id, taken_at, score, max_score) values (tid, now(), p_score, 12);
  end if;
  if p_result = 'passed' then
    perform private.discord_post(format('✅ **%s** passed a tryout (host: %s). An officer can add them to the roster.', trim(p_recruit_name), hname));
  end if;
  return jsonb_build_object('ok', true, 'message', format('Tryout logged: %s %s', trim(p_recruit_name), p_result),
                            'blacklisted', blacklisted);
end $$;

-- ===================================================================== alerts
create or replace function private.alerts() returns jsonb
language sql stable security definer set search_path = '' as $$
  with s as (select key, value from public.setting),
  ready as (
    select b.display_name, b.rank from public.v_promotion_board b
    group by b.membership_id, b.display_name, b.rank having bool_and(b.met))
  select jsonb_build_object(
    'low_hours', coalesce((select jsonb_agg(jsonb_build_object('name', r.display_name, 'rank', r.rank, 'hours', r.hours,
                     'required', r.weekly_hours_required) order by r.rank_order desc, r.hours)
                   from public.v_roster r
                   where r.weekly_hours_required > 0 and r.hours < r.weekly_hours_required
                     and r.status not in ('LOA', 'ROA')), '[]'::jsonb),
    'trainings_7d', (select count(*) from public.training where held_on > public.app_today() - 7),
    'min_trainings', (select value from s where key = 'min_trainings_week'),
    'tryouts_7d', (select count(*) from public.tryout where held_on > public.app_today() - 7),
    'min_tryouts', (select value from s where key = 'min_tryouts_week'),
    'training_overdue', coalesce((select jsonb_agg(jsonb_build_object('name', b.display_name, 'rank', b.rank) order by b.display_name)
                   from public.v_promotion_board b where b.kind = 'hosted_training' and not b.auto_met
                     and b.status not in ('LOA', 'ROA')), '[]'::jsonb),
    'pending_requests', coalesce((select jsonb_agg(jsonb_build_object('name', p.display_name, 'type', q.type,
                     'starts_on', q.starts_on, 'ends_on', q.ends_on) order by q.requested_at)
                   from public.leave_request q join public.person p on p.id = q.person_id where q.status = 'pending'), '[]'::jsonb),
    'leave_ending', coalesce((select jsonb_agg(jsonb_build_object('name', r.display_name, 'type', r.leave_type, 'ends_on', r.leave_ends_on))
                   from public.v_roster r where r.leave_ends_on between public.app_today() and public.app_today() + 1), '[]'::jsonb),
    'ready_for_promotion', coalesce((select jsonb_agg(jsonb_build_object('name', display_name, 'rank', rank) order by rank, display_name) from ready), '[]'::jsonb))
$$;

create or replace function public.co_alerts() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.is_officer() then raise exception 'Only signed-in officers can see alerts.'; end if;

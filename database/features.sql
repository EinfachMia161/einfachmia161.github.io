-- ===================================================================== in-database backups
create table if not exists private.snapshot (
  id bigint generated by default as identity primary key,
  taken_at timestamptz not null default now(),
  table_name text not null,
  row_count int not null,
  rows jsonb not null
);
create index if not exists snapshot_time on private.snapshot (taken_at, table_name);
revoke all on private.snapshot from public, anon, authenticated;

create or replace function private.take_snapshot() returns int
language plpgsql security definer set search_path = '' as $$
declare t text; n int := 0; keep int;
begin
  foreach t in array array['person','person_alias','membership','member_note','rank','requirement','member_requirement',
                           'person_qualification','duty_log','training','training_attendee','tryout','rank_change','strike',
                           'infraction','leave','leave_request','blacklist','blacklist_appeal','medal_award','officer_account',
                           'co_note','co_link','co_document','setting'] loop
    execute format('insert into private.snapshot (table_name, row_count, rows)
                    select %L, count(*), coalesce(jsonb_agg(to_jsonb(x)), ''[]'') from public.%I x', t, t);
    n := n + 1;
  end loop;
  select value::int into keep from public.setting where key = 'snapshot_keep_days';
  delete from private.snapshot where taken_at < now() - make_interval(days => coalesce(keep, 14));
  return n;
end $$;

-- List snapshots:      select taken_at, table_name, row_count from private.snapshot order by taken_at desc;
-- Rows of one table:   select * from private.snapshot_rows('duty_log', '2026-11-03');
create or replace function private.snapshot_rows(p_table text, p_day date) returns setof jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_array_elements(s.rows) from (
    select rows from private.snapshot
    where table_name = p_table and taken_at::date = p_day order by taken_at desc limit 1) s
$$;

revoke all on all functions in schema private from public, anon, authenticated;


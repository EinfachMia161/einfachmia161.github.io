create or replace function private.set_alert_email(p_email text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if p_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'That is not an email address.'; end if;
  insert into private.config (key, value) values ('alert_email', p_email)
  on conflict (key) do update set value = excluded.value;
end $$;

-- ===================================================================== event notifications (Discord)
create or replace function private.notify_change() returns trigger
language plpgsql security definer set search_path = '' as $$
declare n text; f text; t text; r jsonb := to_jsonb(new);
begin
  select display_name into n from public.person where id = (r->>'person_id')::uuid;
  if tg_table_name = 'rank_change' then
    if r->>'kind' in ('promoted', 'demoted') then
      select code into f from public.rank where id = (r->>'from_rank_id')::int;
      select code into t from public.rank where id = (r->>'to_rank_id')::int;
      perform private.discord_post(format('%s **%s** %s: %s → %s',
        case when r->>'kind' = 'promoted' then '⬆️' else '⬇️' end, n, r->>'kind', coalesce(f, '–'), t));
    end if;
  elsif tg_table_name = 'officer_account' then
    perform private.discord_post(format('🔐 Officer login linked for **%s**. If this was not them, remove it in the CO area.', n));
  elsif tg_table_name = 'strike' then
    perform private.discord_post(format('⚠️ Strike (%s) for **%s**', r->>'weight', n));
  end if;
  return new;
end $$;


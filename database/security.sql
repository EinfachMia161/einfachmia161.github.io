-- Officer accounts, the CO registration code, rate limits and every action the website can take.
-- Load order: schema.sql, data.sql, security.sql, policies.sql.
--
-- How editing is protected
--   * Reading is public. Editing needs a Supabase login that is linked to a serving officer (LT or higher).
--   * A login is linked with claim_officer(Steam ID, CO registration code).
--   * The code is stored only as a bcrypt hash in the "private" schema. That schema is not exposed by the
--     Supabase API and the website roles have no rights on it, so neither the hash nor the code can be read.
--   * Failed attempts are rate-limited per login and across all logins.
--   * Rights follow the roster: an officer who is demoted below LT or discharged loses them immediately.

create extension if not exists pgcrypto with schema extensions;

-- ===== Private schema (never exposed) =====
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists private.app_secret (
  name text primary key,
  value_hash text not null,
  updated_at timestamptz not null default now()
);

create table if not exists private.attempt (
  id bigint generated by default as identity primary key,
  kind text not null,              -- 'claim' or 'duty'
  key text not null,               -- login id or Steam ID
  ok boolean not null,
  at timestamptz not null default now()
);
create index if not exists attempt_recent on private.attempt (kind, key, at);
revoke all on all tables in schema private from public, anon, authenticated;

-- Creates a new random CO registration code, stores only its hash and returns the code ONCE.
-- Run it yourself in the Supabase SQL editor:  select private.new_co_registration_code();
-- Running it again replaces the code; the old one stops working at once. Existing officer logins stay linked.
create or replace function private.new_co_registration_code() returns text
language plpgsql security definer set search_path = '' as $$
declare
  raw text := upper(encode(extensions.gen_random_bytes(15), 'hex'));   -- 120 random bits
  code text := 'NU7-' || substr(raw, 1, 6) || '-' || substr(raw, 7, 6) || '-' || substr(raw, 13, 6)
                || '-' || substr(raw, 19, 6) || '-' || substr(raw, 25, 6);
begin
  insert into private.app_secret (name, value_hash, updated_at)
  values ('co_registration_code', extensions.crypt(code, extensions.gen_salt('bf', 12)), now())
  on conflict (name) do update set value_hash = excluded.value_hash, updated_at = now();
  return code;
end $$;
revoke all on function private.new_co_registration_code() from public, anon, authenticated;

-- Turns registration off until a new code is created.
create or replace function private.disable_co_registration() returns void
language sql security definer set search_path = '' as $$
  delete from private.app_secret where name = 'co_registration_code';
$$;
revoke all on function private.disable_co_registration() from public, anon, authenticated;

-- ===== Officer accounts =====
create table if not exists officer_account (
  user_id uuid primary key,                      -- auth.users id (Supabase login)
  person_id uuid not null unique references person on delete cascade,
  linked_at timestamptz not null default now()
);

create or replace function public.is_officer() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.officer_account oa
    join public.membership m on m.person_id = oa.person_id and m.left_at is null
    join public.rank r on r.id = m.rank_id
    where oa.user_id = auth.uid() and r.category_id in (1, 2))
$$;

create or replace function public.is_regcom() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.officer_account oa
    join public.membership m on m.person_id = oa.person_id and m.left_at is null
    join public.rank r on r.id = m.rank_id
    where oa.user_id = auth.uid() and r.category_id = 1)
$$;

-- Who am I? Used by the website after sign-in.
create or replace function public.my_officer() returns table (person_id uuid, display_name text, rank text, is_officer boolean, is_regcom boolean)
language sql stable security definer set search_path = '' as $$
  select p.id, p.display_name, r.code, public.is_officer(), public.is_regcom()
  from public.officer_account oa
  join public.person p on p.id = oa.person_id
  left join public.membership m on m.person_id = p.id and m.left_at is null
  left join public.rank r on r.id = m.rank_id
  where oa.user_id = auth.uid()
$$;

-- Links the signed-in login to a serving officer. Returns {ok, message}; failures are counted, not raised,
-- so the attempt is recorded even though the request fails.
create or replace function public.claim_officer(p_steam_id text, p_code text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
  sid text := regexp_replace(upper(trim(coalesce(p_steam_id, ''))), '^STEAM_1', 'STEAM_0');
  code text := upper(regexp_replace(coalesce(p_code, ''), '\s', '', 'g'));
  h text; pid uuid; pname text;
begin
  if uid is null then
    return jsonb_build_object('ok', false, 'message', 'Sign in first.');
  end if;
  if (select count(*) from private.attempt where kind = 'claim' and key = uid::text and not ok
        and at > now() - interval '15 minutes') >= 5
     or (select count(*) from private.attempt where kind = 'claim' and not ok
        and at > now() - interval '15 minutes') >= 30 then
    return jsonb_build_object('ok', false, 'message', 'Too many failed attempts. Try again in 15 minutes.');
  end if;
  if exists (select 1 from public.officer_account where user_id = uid) then
    return jsonb_build_object('ok', false, 'message', 'This login is already linked to an officer.');
  end if;

  select value_hash into h from private.app_secret where name = 'co_registration_code';
  select p.id, p.display_name into pid, pname
  from public.person p
  join public.membership m on m.person_id = p.id and m.left_at is null
  join public.rank r on r.id = m.rank_id
  where p.steam_id = sid and r.category_id in (1, 2);

  if h is null or length(code) < 10 or extensions.crypt(code, h) <> h
     or pid is null or exists (select 1 from public.officer_account where person_id = pid) then
    insert into private.attempt (kind, key, ok) values ('claim', uid::text, false);
    -- one message for every failure, so nothing can be learned from it
    return jsonb_build_object('ok', false, 'message',
      'Not accepted. Check the registration code and that the Steam ID belongs to an officer (LT or higher) who has no login yet.');
  end if;

  insert into public.officer_account (user_id, person_id) values (uid, pid);
  insert into private.attempt (kind, key, ok) values ('claim', uid::text, true);
  return jsonb_build_object('ok', true, 'message', 'Linked to ' || pname);
end $$;

-- Discord usernames are only visible to officers.
create or replace function public.member_discord() returns table (person_id uuid, discord_username text)
language sql stable security definer set search_path = '' as $$
  select p.id, p.discord_username from public.person p where public.is_officer() and p.discord_username is not null
$$;

-- ===== Hours form for PVT to CSG (no login) =====
-- Identity check: Steam ID + Discord username of a serving PVT-CSG. Discord names are not public.
create or replace function public.submit_duty(p_steam_id text, p_discord text, p_date date, p_hours numeric,
                                              p_comment text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  sid text := regexp_replace(upper(trim(coalesce(p_steam_id, ''))), '^STEAM_1', 'STEAM_0');
  pid uuid; pname text; rid int; disc text; day_total numeric; week_total numeric;
  today date := public.app_today();
begin
  if (select count(*) from private.attempt where kind = 'duty' and key = sid and not ok
        and at > now() - interval '15 minutes') >= 5
     or (select count(*) from private.attempt where kind = 'duty' and not ok
        and at > now() - interval '15 minutes') >= 60 then
    return jsonb_build_object('ok', false, 'message', 'Too many failed attempts. Try again in 15 minutes.');
  end if;

  select p.id, p.display_name, m.rank_id, lower(trim(p.discord_username)) into pid, pname, rid, disc
  from public.person p
  join public.membership m on m.person_id = p.id and m.left_at is null
  join public.rank r on r.id = m.rank_id
  where p.steam_id = sid and r.category_id in (3, 4);

  if pid is null or disc is null or disc <> lower(trim(coalesce(p_discord, ''))) then
    insert into private.attempt (kind, key, ok) values ('duty', sid, false);
    return jsonb_build_object('ok', false, 'message',
      'Steam ID and Discord username do not match a serving PVT to CSG. Officers log their hours through an officer.');
  end if;

  if p_hours is null or p_hours <= 0 or p_hours > 12 then
    return jsonb_build_object('ok', false, 'message', 'Hours must be more than 0 and at most 12 per entry.');
  end if;
  if p_date is null or p_date > today or p_date < today - 6 then
    return jsonb_build_object('ok', false, 'message', 'The date must be today or within the last 6 days.');
  end if;
  if length(coalesce(p_comment, '')) > 300 then
    return jsonb_build_object('ok', false, 'message', 'Keep the comment under 300 characters.');
  end if;
  select coalesce(sum(hours), 0) into day_total from public.duty_log
   where person_id = pid and logged_on = p_date and not rejected;
  if day_total + p_hours > 16 then
    return jsonb_build_object('ok', false, 'message', 'That would be more than 16 hours on one day.');
  end if;
  if (select count(*) from public.duty_log where person_id = pid and source = 'self'
        and logged_at > now() - interval '1 day') >= 10 then
    return jsonb_build_object('ok', false, 'message', 'Daily limit of 10 entries reached. Ask an officer.');
  end if;

  insert into public.duty_log (person_id, logged_on, hours, rank_id, comment, source)
  values (pid, p_date, round(p_hours, 1), rid, nullif(trim(p_comment), ''), 'self');
  insert into private.attempt (kind, key, ok) values ('duty', sid, true);

  select coalesce(sum(hours), 0) into week_total from public.duty_log
   where person_id = pid and not rejected and logged_on <= today
     and logged_on >= today - (select value::int from public.setting where key = 'activity_window_days');
  return jsonb_build_object('ok', true, 'message', 'Logged ' || round(p_hours, 1) || ' h for ' || pname,
                            'week_hours', week_total);
end $$;

-- ===== Officer actions (each runs as one transaction) =====
create or replace function public.change_rank(p_membership uuid, p_to_rank text, p_kind text, p_officer text default null,
                                              p_comment text default null) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare m membership; to_id int;
begin
  if not public.is_officer() then raise exception 'Only signed-in officers can change ranks.'; end if;
  select * into m from membership where id = p_membership and left_at is null for update;
  if not found then raise exception 'This member is not on the roster any more.'; end if;
  select id into to_id from rank where code = upper(p_to_rank);
  if to_id is null then raise exception 'Unknown rank "%".', p_to_rank; end if;
  if to_id = m.rank_id then raise exception 'The member already holds this rank.'; end if;
  if p_kind not in ('promoted', 'demoted') then raise exception 'Choose promoted or demoted.'; end if;
  if p_kind = 'promoted' and to_id < m.rank_id then raise exception 'A promotion has to go to a higher rank.'; end if;
  if p_kind = 'demoted' and to_id > m.rank_id then raise exception 'A demotion has to go to a lower rank.'; end if;
  insert into rank_change (person_id, from_rank_id, to_rank_id, kind, effective_on, officer_raw, comment)
  values (m.person_id, m.rank_id, to_id, p_kind, app_today(), nullif(trim(p_officer), ''), nullif(trim(p_comment), ''));
  update membership set rank_id = to_id where id = m.id;
end $$;

create or replace function public.add_member(p_steam_id text, p_name text, p_discord text default null,
                                             p_rank text default 'PVT', p_override boolean default false) returns uuid
language plpgsql security definer set search_path = public, pg_temp as $$
declare pid uuid; rid int; mid uuid; sid text := upper(trim(p_steam_id));
begin
  if not public.is_officer() then raise exception 'Only signed-in officers can add members.'; end if;
  if sid !~ '^STEAM_[01]:[01]:[0-9]+$' then raise exception 'Steam ID must look like STEAM_0:1:12345678.'; end if;
  sid := regexp_replace(sid, '^STEAM_1', 'STEAM_0');
  if coalesce(trim(p_name), '') = '' then raise exception 'Enter a name.'; end if;
  select id into rid from rank where code = upper(p_rank);
  if rid is null then raise exception 'Unknown rank "%".', p_rank; end if;
  if not p_override and exists (select 1 from v_active_blacklist where steam_id = sid) then
    raise exception 'This Steam ID is blacklisted. Revoke the blacklist entry first or confirm the override.';
  end if;
  select id into pid from person where steam_id = sid;
  if pid is null then
    insert into person (steam_id, display_name, discord_username)
    values (sid, trim(p_name), nullif(trim(p_discord), '')) returning id into pid;
  else
    if exists (select 1 from membership where person_id = pid and left_at is null) then
      raise exception 'This Steam ID is already on the roster.';
    end if;
    update person set display_name = trim(p_name),
                      discord_username = coalesce(nullif(trim(p_discord), ''), discord_username) where id = pid;
  end if;
  insert into person_alias (person_id, name, first_seen) values (pid, trim(p_name), app_today()) on conflict do nothing;
  insert into membership (person_id, rank_id, recruited_at) values (pid, rid, app_today()) returning id into mid;
  return mid;
end $$;

create or replace function public.discharge_member(p_membership uuid, p_type text, p_reason text default null,
                                                   p_officer text default null) returns void
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not public.is_officer() then raise exception 'Only signed-in officers can discharge members.'; end if;
  if p_type not in ('honourable', 'dishonourable') then raise exception 'Choose honourable or dishonourable.'; end if;
  update membership set left_at = app_today(), discharge_type = p_type,
         discharge_reason = nullif(trim(p_reason), ''), discharged_by_raw = nullif(trim(p_officer), '')
  where id = p_membership and left_at is null;
  if not found then raise exception 'This member is not on the roster any more.'; end if;
end $$;
